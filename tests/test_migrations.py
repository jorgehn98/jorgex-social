import sqlite3

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from jorgex_social.cli import alembic_config


def test_models_match_migrations(settings):
    try:
        command.check(alembic_config(settings))
    except AutogenerateDiffsDetected as exc:
        raise AssertionError(f"models and migrations differ; add a migration: {exc}") from None


def test_downgrade_and_upgrade_again(settings):
    config = alembic_config(settings)

    command.downgrade(config, "base")
    command.upgrade(config, "head")


def test_the_comment_author_column_keeps_existing_rows(settings):
    config = alembic_config(settings)
    command.downgrade(config, "0011")
    with sqlite3.connect(settings.database_path) as db:
        db.execute(
            "INSERT INTO rules (id, network, name, channel, priority, active, content, created_at,"
            " updated_at) VALUES ('r', 'n', 'x', 'comment', 1, 0, '{}', 't', 't')"
        )
        db.execute(
            "INSERT INTO events (id, network, type, external_ref, occurred_at, received_at)"
            " VALUES ('e', 'n', 'comment', 'c1', 't', 't')"
        )
        db.execute(
            "INSERT INTO deliveries (id, event_id, rule_id, action, status, text, created_at)"
            " VALUES ('d', 'e', 'r', 'public_reply', 'sent', 'hi', 't')"
        )

    command.upgrade(config, "head")

    with sqlite3.connect(settings.database_path) as db:
        assert db.execute("SELECT id, author_ref FROM events").fetchall() == [("e", None)]
        assert db.execute("SELECT id FROM deliveries").fetchall() == [("d",)]

    command.downgrade(config, "0011")

    with sqlite3.connect(settings.database_path) as db:
        assert db.execute("SELECT id FROM events").fetchall() == [("e",)]
        assert db.execute("SELECT id FROM deliveries").fetchall() == [("d",)]
