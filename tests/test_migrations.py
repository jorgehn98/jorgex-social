def test_the_comment_author_column_keeps_existing_rows(settings):
    config = alembic_config(settings)
    command.downgrade(config, "0011")
    with sqlite3.connect(settings.database_path) as db:
        db.execute(
            "INSERT INTO rules (id, network, name, channel, priority, active, content, created_at,"
            " updated_at) VALUES ('r', 'n', 'x', 'comment', 1, 0, '{}', 't', 't')"
        )
        db.execute(
            "INSERT INTO events (id, network, type, external_ref, occurred_at, received_at)"
            " VALUES ('e', 'n', 'comment', 'c1', 't', 't')"
        )
        db.execute(
            "INSERT INTO deliveries (id, event_id, rule_id, action, status, text, created_at)"
            " VALUES ('d', 'e', 'r', 'public_reply', 'sent', 'hi', 't')"
        )

    command.upgrade(config, "head")

    with sqlite3.connect(settings.database_path) as db:
        assert db.execute("SELECT id, author_ref FROM events").fetchall() == [("e", None)]
        assert db.execute("SELECT id FROM deliveries").fetchall() == [("d",)]

    command.downgrade(config, "0011")

    with sqlite3.connect(settings.database_path) as db:
        assert db.execute("SELECT id FROM events").fetchall() == [("e",)]
        assert db.execute("SELECT id FROM deliveries").fetchall() == [("d",)]


def test_the_rule_post_column_keeps_existing_rows(settings):
    config = alembic_config(settings)
    command.downgrade(config, "0013")
    with sqlite3.connect(settings.database_path) as db:
        db.execute(
            "INSERT INTO rules (id, network, name, channel, media_ref, priority, active, content,"
            " created_at, updated_at)"
            " VALUES ('r', 'n', 'x', 'comment', 'm1', 1, 0, '{}', 't', 't')"
        )
        db.execute(
            "INSERT INTO events (id, network, type, external_ref, occurred_at, received_at,"
            " rule_id) VALUES ('e', 'n', 'comment', 'c1', 't', 't', 'r')"
        )
        db.execute(
            "INSERT INTO deliveries (id, event_id, rule_id, action, status, text, created_at)"
            " VALUES ('d', 'e', 'r', 'public_reply', 'sent', 'hi', 't')"
        )

    command.upgrade(config, "head")

    with sqlite3.connect(settings.database_path) as db:
        assert db.execute("SELECT id, media_ref, post_id FROM rules").fetchall() == [
            ("r", "m1", None)
        ]
        references = db.execute("PRAGMA foreign_key_list(rules)").fetchall()
        assert [(f[2], f[3], f[4]) for f in references] == [
            ("connections", "account_id", "id"),
            ("posts", "post_id", "id"),
        ]
        assert db.execute("PRAGMA foreign_key_check").fetchall() == []
        account_id = db.execute("SELECT account_id FROM rules WHERE id = 'r'").fetchone()[0]
        db.execute(
            "INSERT INTO posts (id, account_id, type, status, caption, content_hash, created_at,"
            " updated_at) VALUES ('p', ?, 'image', 'draft', '', 'h', 't', 't')",
            (account_id,),
        )
        for rule_id, media_ref in (("waiting", None), ("bound", "m2")):
            db.execute(
                "INSERT INTO rules (id, account_id, name, channel, media_ref, post_id, priority,"
                " active, activated_at, content, created_at, updated_at) VALUES"
                " (?, ?, 'x', 'comment', ?, 'p', 1, 1, 't', '{}', 't', 'edited')",
                (rule_id, account_id, media_ref),
            )

    command.downgrade(config, "0013")

    with sqlite3.connect(settings.database_path) as db:
        found = db.execute(
            "SELECT id, media_ref, active, archived_at FROM rules ORDER BY id"
        ).fetchall()
        # The waiting rule must not come back as a rule for every post.
        assert found == [
            ("bound", "m2", 1, None),
            ("r", "m1", 0, None),
            ("waiting", None, 0, "edited"),
        ]
        assert "post_id" not in [c[1] for c in db.execute("PRAGMA table_info(rules)")]
        assert db.execute("PRAGMA foreign_key_list(rules)").fetchall() == []
        assert db.execute("SELECT id FROM deliveries").fetchall() == [("d",)]
        assert db.execute("PRAGMA foreign_key_check").fetchall() == []


def test_downgrading_trial_returns_scheduled_trial_reels_to_draft(settings):
    config = alembic_config(settings)
    command.upgrade(config, "head")
    with sqlite3.connect(settings.database_path) as db:
        db.execute(
            "INSERT INTO connections (id, network, external_account_id, username, status)"
            " VALUES ('c', 'instagram', '1784', 'account', 'ok')"
        )
        for post_id, status, trial in [
            ("trial", "scheduled", "manual"),
            ("plain", "scheduled", None),
            ("draft", "draft", "auto"),
        ]:
            db.execute(
                "INSERT INTO posts (id, account_id, type, status, caption, scheduled_for, trial,"
                " content_hash, created_at, updated_at)"
                " VALUES (?, 'c', 'reel', ?, 'c', 's', ?, 'h', 't', 't')",
                (post_id, status, trial),
            )

    command.downgrade(config, "0014")

    with sqlite3.connect(settings.database_path) as db:
        rows = db.execute("SELECT id, status, scheduled_for FROM posts ORDER BY id").fetchall()
    assert rows == [("draft", "draft", "s"), ("plain", "scheduled", "s"), ("trial", "draft", None)]


# The account as the key of the domain (0016)

REAL = "connection-real"
# Every table the migration gives an account to, and the ones it leaves as they were but must not
# touch (`post_items` and `publish_attempts` reach their account through the post).
WITH_ACCOUNT = (
    "posts",
    "media",
    "post_snapshots",
    "account_snapshots",
    "recent_media",
    "rules",
    "events",
    "deliveries",
    "conversations",
    "channel_incidents",
)
COUNTED = (*WITH_ACCOUNT, "post_items", "publish_attempts", "audit_log")


def _populate(db) -> None:
    """One account with rows of both networks: the real one, which is connected, and the
    simulation, which never was."""
    db.execute(
        "INSERT INTO connections (id, network, external_account_id, username, status,"
        " credential_encrypted) VALUES (?, 'instagram', '1784', 'account', 'ok', ?)",
        (REAL, b"sealed-with-the-network-context"),
    )
    db.execute(
        "INSERT INTO settings (key, value, updated_at) VALUES ('kill_switch', 'true', 'now')"
    )
    for network in ("instagram", "simulation"):
        db.execute(
            "INSERT INTO media (id, relative_path, sha256, type, bytes, created_at)"
            " VALUES (?, ?, '', 'jpeg', 1, 'now')",
            (f"media-{network}", f"{network}.jpeg"),
        )
        db.execute(
            "INSERT INTO posts (id, network, type, status, caption, external_ref,"
            " idempotency_key, content_hash, created_at, updated_at)"
            " VALUES (?, ?, 'image', 'published', '', ?, ?, 'h', 'now', 'now')",
            (f"post-{network}", network, f"ref-{network}", f"key-{network}"),
        )
        db.execute(
            "INSERT INTO post_items (post_id, position, media_id) VALUES (?, 0, ?)",
            (f"post-{network}", f"media-{network}"),
        )
        db.execute(
            "INSERT INTO publish_attempts (id, post_id, number, started_at, result)"
            " VALUES (?, ?, 1, 'now', 'ok')",
            (f"attempt-{network}", f"post-{network}"),
        )
        db.execute(
            "INSERT INTO post_snapshots (network, media_ref, taken_at, product_type,"
            " published_at, metrics) VALUES (?, 'm1', ?, 'FEED', 'now', '{}')",
            (network, f"taken-{network}"),
        )
        db.execute(
            "INSERT INTO account_snapshots (network, period_start, period_end, taken_at,"
            " metrics) VALUES (?, ?, 'b', 'now', '{}')",
            (network, f"start-{network}"),
        )
        db.execute(
            "INSERT INTO recent_media (network, fetched_at, items) VALUES (?, ?, '[]')",
            (network, f"fetched-{network}"),
        )
        db.execute(
            "INSERT INTO rules (id, network, name, channel, priority, active, content,"
            " created_at, updated_at) VALUES (?, ?, 'r', 'comment', 1, 0, '{}', 'n', 'n')",
            (f"rule-{network}", network),
        )
        db.execute(
            "INSERT INTO conversations (id, network, external_id, last_user_message_at,"
            " window_until, paused_forever, created_at, updated_at, purge_at)"
            " VALUES (?, ?, 'person', 'now', 'now', 0, 'now', 'now', 'now')",
            (f"conversation-{network}", network),
        )
        db.execute(
            "INSERT INTO events (id, network, type, external_ref, occurred_at, received_at)"
            " VALUES (?, ?, 'comment', 'c1', 'now', 'now')",
            (f"event-{network}", network),
        )
        db.execute(
            "INSERT INTO deliveries (id, event_id, rule_id, action, status, text, created_at)"
            " VALUES (?, ?, ?, 'public_reply', 'sent', 'hi', 'now')",
            (f"delivery-{network}", f"event-{network}", f"rule-{network}"),
        )
        db.execute(
            "INSERT INTO channel_incidents (id, network, type, opened_at)"
            " VALUES (?, ?, 'persistent_api_error', 'now')",
            (f"incident-{network}", network),
        )
    db.execute(
        "INSERT INTO audit_log (id, occurred_at, actor_type, action, outcome)"
        " VALUES ('a', 'now', 'operator', 'operator.login', 'ok')"
    )


def _counts(db) -> dict[str, int]:
    return {table: db.execute(f"SELECT count(*) FROM {table}").fetchone()[0] for table in COUNTED}


def _accounts(db) -> dict[tuple[str, str], str]:
    """(table, id) -> account, for every row the migration touched."""
    found = {("posts", row[0]): row[1] for row in db.execute("SELECT id, account_id FROM posts")}
    for table, column in (
        ("rules", "id"),
        ("events", "id"),
        ("deliveries", "id"),
        ("conversations", "id"),
        ("channel_incidents", "id"),
        ("media", "id"),
        ("post_snapshots", "taken_at"),
        ("account_snapshots", "period_start"),
        ("recent_media", "fetched_at"),
    ):
        query = f"SELECT {column}, account_id FROM {table}"
        found |= {(table, row[0]): row[1] for row in db.execute(query)}
    return found


def test_the_account_replaces_the_network_and_every_row_keeps_its_data(settings):
    config = alembic_config(settings)
    command.downgrade(config, "0015")
    with sqlite3.connect(settings.database_path) as db:
        _populate(db)
        before = _counts(db)

    command.upgrade(config, "head")

    with sqlite3.connect(settings.database_path) as db:
        # Nothing was lost, and every row belongs to an account: its own network's.
        assert _counts(db) == before
        simulation = db.execute(
            "SELECT id FROM connections WHERE network = 'simulation'"
        ).fetchone()[0]
        assert simulation != REAL
        assert db.execute(
            "SELECT external_account_id FROM connections WHERE id = ?", (simulation,)
        ).fetchone() == ("",)
        accounts = _accounts(db)
        for (table, row), account_id in accounts.items():
            expected = simulation if "simulation" in str(row) else REAL
            assert account_id == expected, (table, row)
        assert accounts[("deliveries", "delivery-simulation")] == simulation
        assert {row for row in db.execute("SELECT account_id FROM audit_log")} == {(None,)}
        assert db.execute("PRAGMA foreign_key_check").fetchall() == []
        # No domain row is left without one.
        for table in WITH_ACCOUNT:
            assert db.execute(
                f"SELECT count(*) FROM {table} WHERE account_id IS NULL"
            ).fetchone() == (0,)

        # The installation's switch moved to every account, the one the migration created too, and
        # left settings.
        assert {row for row in db.execute("SELECT id, kill_switch FROM connections")} == {
            (REAL, 1),
            (simulation, 1),
        }
        # Only the row that already held a credential may open the network's context, and only until
        # it is sealed again.
        assert {row for row in db.execute("SELECT id, credential_legacy FROM connections")} == {
            (REAL, 1),
            (simulation, 0),
        }
        assert db.execute("SELECT count(*) FROM settings WHERE key = 'kill_switch'").fetchone() == (
            0,
        )

        # The snapshots and the recent media are keyed by account first.
        for table in ("post_snapshots", "account_snapshots", "recent_media"):
            info = db.execute(f"PRAGMA table_info({table})").fetchall()
            assert next(row[5] for row in info if row[1] == "account_id") == 1, table
            assert "network" not in {row[1] for row in info}

        # The unique keys are per account: the same value fits the other account, not its own.
        def refuses(sql, params=()):
            with pytest.raises(sqlite3.IntegrityError):
                db.execute(sql, params)

        refuses(
            "INSERT INTO posts (id, account_id, type, status, caption, external_ref,"
            " content_hash, created_at, updated_at)"
            " VALUES ('other', ?, 'image', 'draft', '', 'ref-instagram', 'h', 'n', 'n')",
            (REAL,),
        )
        refuses(
            "INSERT INTO posts (id, account_id, type, status, caption, idempotency_key,"
            " content_hash, created_at, updated_at)"
            " VALUES ('other', ?, 'image', 'draft', '', 'key-instagram', 'h', 'n', 'n')",
            (REAL,),
        )
        # The same caller key and media ref, in the other account, are another row.
        db.execute(
            "INSERT INTO posts (id, account_id, type, status, caption, external_ref,"
            " idempotency_key, content_hash, created_at, updated_at)"
            " VALUES ('mine', ?, 'image', 'draft', '', 'ref-instagram', 'key-instagram', 'h',"
            " 'n', 'n')",
            (simulation,),
        )
        refuses(
            "INSERT INTO events (id, account_id, type, external_ref, occurred_at, received_at)"
            " VALUES ('other', ?, 'comment', 'c1', 'now', 'now')",
            (REAL,),
        )
        refuses(
            "INSERT INTO conversations (id, account_id, external_id, last_user_message_at,"
            " window_until, paused_forever, created_at, updated_at, purge_at)"
            " VALUES ('other', ?, 'person', 'now', 'now', 0, 'now', 'now', 'now')",
            (REAL,),
        )
        refuses(
            "INSERT INTO channel_incidents (id, account_id, type, opened_at)"
            " VALUES ('other', ?, 'persistent_api_error', 'now')",
            (REAL,),
        )

        # The audit log is still append-only.
        for statement in ("UPDATE audit_log SET outcome = 'ok'", "DELETE FROM audit_log"):
            with pytest.raises(sqlite3.IntegrityError, match="append-only"):
                db.execute(statement)


def test_downgrading_brings_the_network_and_the_installations_switch_back(settings):
    config = alembic_config(settings)
    command.downgrade(config, "0015")
    with sqlite3.connect(settings.database_path) as db:
        _populate(db)
        before = _counts(db)

    command.upgrade(config, "head")
    command.downgrade(config, "0015")

    with sqlite3.connect(settings.database_path) as db:
        assert _counts(db) == before
        assert {row for row in db.execute("SELECT DISTINCT network FROM posts")} == {
            ("instagram",),
            ("simulation",),
        }
        assert db.execute("SELECT network FROM post_snapshots ORDER BY taken_at").fetchall() == [
            ("instagram",),
            ("simulation",),
        ]
        assert db.execute(
            "SELECT network FROM account_snapshots ORDER BY period_start"
        ).fetchall() == [("instagram",), ("simulation",)]
        assert db.execute("SELECT network FROM recent_media ORDER BY fetched_at").fetchall() == [
            ("instagram",),
            ("simulation",),
        ]
        assert "account_id" not in {row[1] for row in db.execute("PRAGMA table_info(posts)")}
        assert "credential_legacy" not in {
            row[1] for row in db.execute("PRAGMA table_info(connections)")
        }
        assert db.execute("PRAGMA foreign_key_check").fetchall() == []
        assert db.execute("SELECT value FROM settings WHERE key = 'kill_switch'").fetchone() == (
            "true",
        )
        for statement in ("UPDATE audit_log SET outcome = 'ok'", "DELETE FROM audit_log"):
            with pytest.raises(sqlite3.IntegrityError, match="append-only"):
                db.execute(statement)


def test_an_operator_incident_stays_without_an_account(settings):
    """The sign-in warning is not an account's: the credential commands are what close it, and they
    close the one without an account."""
    config = alembic_config(settings)
    command.downgrade(config, "0015")
    with sqlite3.connect(settings.database_path) as db:
        db.execute(
            "INSERT INTO connections (id, network, external_account_id, username, status)"
            " VALUES (?, 'instagram', '1784', 'account', 'ok')",
            (REAL,),
        )
        db.execute(
            "INSERT INTO channel_incidents (id, network, type, opened_at)"
            " VALUES ('operator', 'instagram', 'sign_in_password_accepted', ?)",
            ("2026-11-01T00:00:00.000000+00:00",),
        )

    command.upgrade(config, "head")

    with sqlite3.connect(settings.database_path) as db:
        assert db.execute("SELECT account_id, closed_at FROM channel_incidents").fetchall() == [
            (None, None)
        ]
        # A second open one of the same cause is refused, NULL account notwithstanding.
        with pytest.raises(sqlite3.IntegrityError):
            db.execute(
                "INSERT INTO channel_incidents (id, account_id, type, opened_at)"
                " VALUES ('another', NULL, 'sign_in_password_accepted',"
                " '2026-11-01T00:00:00.000000+00:00')"
            )

    sessions = make_sessionmaker(make_engine(settings))
    with sessions() as session, session.begin():
        operator.create_operator(session, "a long enough password", datetime.now(UTC))
        operator.set_password(session, "another long enough password", datetime.now(UTC))

    with sqlite3.connect(settings.database_path) as db:
        closed_at = db.execute("SELECT closed_at FROM channel_incidents").fetchone()[0]
    assert closed_at is not None

    # The old schema names it after the installation's only network, and needs it not open twice.
    command.downgrade(config, "0015")
    with sqlite3.connect(settings.database_path) as db:
        assert db.execute("SELECT network, closed_at FROM channel_incidents").fetchall() == [
            ("instagram", closed_at)
        ]
        assert db.execute("PRAGMA foreign_key_check").fetchall() == []
